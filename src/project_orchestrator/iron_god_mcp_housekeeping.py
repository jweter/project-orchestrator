"""Bounded read-only MCP projection of the existing engine storage receipt.

The source is generated by the current product-lane idle maintenance hook.
MCP cannot start maintenance, delete files, or acquire owner/worker authority.
"""
from __future__ import annotations

import json
from datetime import UTC, datetime
from pathlib import Path
from typing import Any

MAX_RECEIPT_BYTES = 64_000
FRESH_SECONDS = 900
_ALLOWED_BANDS = frozenset({"GREEN", "YELLOW", "ORANGE", "RED", "CRITICAL", "UNKNOWN"})
_ALLOWED_OUTCOMES = frozenset({"NOT_DUE", "REPORTED", "FAILED"})
_ALLOWED_COUNTS = frozenset({"OBSERVED", "ABSENT", "UNREADABLE", "LINK_PROTECTED",
                             "UNEXPECTED_PATH_TYPE"})


def _integer(value: Any) -> int | None:
    return value if type(value) is int and 0 <= value <= 10**15 else None


def _timestamp(value: Any) -> datetime | None:
    if not isinstance(value, str):
        return None
    try:
        stamp = datetime.fromisoformat(value.replace("Z", "+00:00"))
    except ValueError:
        return None
    return stamp.astimezone(UTC) if stamp.tzinfo is not None else None


def _count(entry: Any) -> dict[str, Any]:
    if not isinstance(entry, dict) or not isinstance(entry.get("status"), str) \
            or entry["status"] not in _ALLOWED_COUNTS:
        return {"status": "UNVERIFIED", "count": None}
    status = entry["status"]
    value = _integer(entry.get("count"))
    if status in {"OBSERVED", "ABSENT"} and value is not None:
        return {"status": status, "count": value}
    return {"status": status, "count": None}


def housekeeping_snapshot(state_root: Path, *, now: datetime | None = None) -> dict[str, Any]:
    """Read the fixed receipt path only, and omit any raw paths or free-form diagnostics.

    Source JSON, its timestamp and disk usage are observational, not proof of
    independent cleanup, an active worker, or permission to delete anything.
    """
    root = Path(state_root)
    if not root.is_absolute():
        raise ValueError("ABSOLUTE_STATE_ROOT_REQUIRED")
    receipt = root / "iron-god-products" / "reports" / "storage-housekeeping.json"
    unavailable = {
        "schema_version": 1, "source": "ENGINE_STORAGE_RECEIPT",
        "status": "UNAVAILABLE", "freshness": "UNVERIFIED",
        "can_execute": False,
    }
    try:
        if receipt.is_symlink() or not receipt.is_file() or receipt.stat().st_size > MAX_RECEIPT_BYTES:
            return unavailable
        raw = json.loads(receipt.read_text(encoding="utf-8"))
    except (OSError, ValueError, UnicodeError):
        return unavailable
    if not isinstance(raw, dict) or raw.get("schema_version") != 1:
        return unavailable
    if raw.get("mode") != "READ_ONLY_ACCOUNTING_NO_DELETION":
        return unavailable
    observed = _timestamp(raw.get("observed_at_utc"))
    if observed is None:
        return unavailable
    clock = now or datetime.now(UTC)
    age = (clock.astimezone(UTC) - observed).total_seconds()
    freshness = "FRESH" if -120 <= age <= FRESH_SECONDS else "STALE"
    disk = raw.get("disk")
    disk = disk if isinstance(disk, dict) else {}
    total = _integer(disk.get("total_bytes"))
    free = _integer(disk.get("free_bytes"))
    measured = total is not None and total > 0 and free is not None and free <= total
    band = disk.get("band")
    band = band if isinstance(band, str) and band in _ALLOWED_BANDS else "UNKNOWN"
    if not measured or disk.get("status") != "OBSERVED":
        band = "UNKNOWN"
    counts = raw.get("counts")
    counts = counts if isinstance(counts, dict) else {}
    maintenance = raw.get("last_cleanup")
    maintenance = maintenance if isinstance(maintenance, dict) else {}
    outcome = maintenance.get("status")
    outcome = (outcome if isinstance(outcome, str) and outcome in _ALLOWED_OUTCOMES
               else "UNVERIFIED")
    return {
        "schema_version": 1,
        "source": "ENGINE_STORAGE_RECEIPT",
        "status": "OK" if freshness == "FRESH" else "STALE",
        "freshness": freshness,
        "observed_at_utc": observed.isoformat(),
        "disk": {
            "band": band,
            "free_gib": round(free / 2**30, 2) if measured and free is not None else None,
            "total_gib": round(total / 2**30, 2) if measured and total is not None else None,
        },
        "counts": {
            "product_worktrees": _count(counts.get("product_worktrees")),
            "recovery_archive_files": _count(counts.get("recovery_archive_files")),
        },
        "maintenance": {
            "status": outcome,
            "reported_removed": _integer(maintenance.get("removed")) if outcome == "REPORTED" else None,
            "remaining_eligible": _integer(maintenance.get("left_for_next_run")) if outcome == "REPORTED" else None,
        },
        "free_space_delta_attributable_to_cleanup": False,
        "can_execute": False,
    }
